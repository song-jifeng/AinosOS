/*
 * Initialize the framebuffer
 */
int framebuffer_init(framebuffer_t *fb, uint64_t phys_addr, uint32_t width,
                      uint32_t height, uint32_t pitch, uint32_t bpp) {
    if (!fb) return -1;

    fb->physical_addr = phys_addr;
    fb->virtual_addr = phys_addr;  /* Identity mapped for now */
    fb->width = width;
    fb->height = height;
    fb->pitch = pitch;
    fb->bpp = bpp;
    fb->size = pitch * height;

    /* Determine pixel format */
    if (bpp == 32) {
        fb->format = FB_FORMAT_RGB888;
        fb->red_mask   = 0x00FF0000;
        fb->green_mask = 0x0000FF00;
        fb->blue_mask  = 0x000000FF;
        fb->red_shift   = 16;
        fb->green_shift = 8;
        fb->blue_shift  = 0;
    } else if (bpp == 24) {
        fb->format = FB_FORMAT_RGB888;
        fb->red_mask   = 0xFF0000;
        fb->green_mask = 0x00FF00;
        fb->blue_mask  = 0x0000FF;
        fb->red_shift   = 16;
        fb->green_shift = 8;
        fb->blue_shift  = 0;
    } else if (bpp == 16) {
        fb->format = FB_FORMAT_RGB565;
        fb->red_mask   = 0xF800;
        fb->green_mask = 0x07E0;
        fb->blue_mask  = 0x001F;
        fb->red_shift   = 11;
        fb->green_shift = 5;
        fb->blue_shift  = 0;
    } else {
        fb->format = FB_FORMAT_UNKNOWN;
    }

    fb->initialized = 1;

    boot_printf(BOOT_LOG_OK "Framebuffer: %ux%u, %u bpp, pitch %u\n",
                width, height, bpp, pitch);

    return 0;
}

/*
 * Create a color value from R, G, B components
 */
uint32_t framebuffer_make_color(framebuffer_t *fb, uint8_t r, uint8_t g, uint8_t b) {
    if (fb->bpp == 32) {
        return (r << fb->red_shift) | (g << fb->green_shift) | (b << fb->blue_shift);
    } else if (fb->bpp == 16) {
        return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3);
    }
    return 0;
}

/*
 * Clear the framebuffer with a color
 */
void framebuffer_clear(framebuffer_t *fb, uint32_t color) {
    if (!fb || !fb->initialized) return;

    if (fb->bpp == 32) {
        uint32_t *buf = (uint32_t*)(uint64_t)fb->virtual_addr;
        for (uint32_t i = 0; i < fb->width * fb->height; i++) {
            buf[i] = color;
        }
    } else {
        uint8_t *buf = (uint8_t*)(uint64_t)fb->virtual_addr;
        for (uint32_t i = 0; i < fb->size; i += fb->bpp / 8) {
            *(uint32_t*)(buf + i) = color;
        }
    }
}

